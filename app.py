import streamlit as st
from pythainlp.tokenize import syllable_tokenize

# ฟังก์ชันสำหรับเช็กว่าคำนั้นมีรูปวรรณยุกต์อะไร หรือเป็นคำตายไหม
def ตรวจสอบประเภทคำ(คำ):
    if "่" in คำ:
        return "เอก"
    elif "้" in คำ:
        return "โท"
    
    # เช็กคำตายเบื้องต้น (ลงท้ายด้วย แม่กก กบ กด หรือสระเสียงสั้นไม่มีตัวสะกด)
    # คำตายสามารถใช้แทน "คำเอก" ในโคลงสี่สุภาพได้
    คำตาย_แม่ = ["ก", "บ", "ด"]
    for แม่ in คำตาย_แม่:
        if คำ.endswith(แม่):
            return "คำตาย (ใช้แทนเอกได้)"
            
    return "ทั่วไป"

# --- ส่วนการแสดงผลหน้าเว็บ ---
st.set_page_config(page_title="ระบบตรวจโคลงสี่สุภาพ", page_icon="✒️")
st.title("✒️ ระบบตรวจสอบฉันทลักษณ์โคลงสี่สุภาพ")
st.subheader("จัดทำขึ้นเพื่อนักเรียนและบุคคลทั่วไป")

# ช่องให้พิมพ์โคลง
ข้อความจากผู้ใช้ = st.text_area("วางโคลงสี่สุภาพของคุณที่นี่ (บรรทัดละ 1 บาท รวม 4 บรรทัด):", height=200, placeholder="ตัวอย่าง:\nเสียงลือเสียงเล่าอ้าง อันใด พี่เอย...\n...")

if st.button("🚀 เริ่มตรวจสอบโคลง"):
    if not ข้อความจากผู้ใช้:
        st.warning("⚠️ กรุณาพิมพ์หรือวางข้อความโคลงก่อนครับ")
    else:
        # แยกข้อความออกเป็นแต่ละบรรทัด
        บรรทัดทั้งหมด = [บ.strip() for บ in ข้อความจากผู้ใช้.split('\n') if บ.strip()]
        
        if len(บรรทัดทั้งหมด) != 4:
            st.error(f"❌ โคลงสี่สุภาพต้องมี 4 บรรทัด (4 บาท) แต่คุณพิมพ์มา {len(บรรทัดทั้งหมด)} บรรทัด กรุณาตรวจสอบอีกครั้ง")
        else:
            st.success("🎉 ตรวจสอบจำนวนบาทถูกต้อง! มาดูรายละเอียดแต่ละบาทกันครับ:")
            
            # วนลูปตรวจทีละบรรทัด
            for ลำดับ, ข้อความบาท in enumerate(บรรทัดทั้งหมด):
                # ใช้ PyThaiNLP ตัดคำออกมาเป็นพยางค์
                พยางค์ทั้งหมด = syllable_tokenize(ข้อความบาท)
                
                st.markdown(f"### 📍 บาทที่ {ลำดับ+1}")
                st.write(f"**ข้อความ:** {ข้อความบาท}")
                st.write(f"**นับได้:** {len(พยางค์ทั้งหมด)} พยางค์")
                
                # แสดงการวิเคราะห์พยางค์ย่อย
                ผลวิเคราะห์ = []
                for พยางค์ in พยางค์ทั้งหมด:
                    ประเภท = ตรวจสอบประเภทคำ(พยางค์)
                    ผลวิเคราะห์.append(f"{พยางค์} ({ประเภท})")
                
                st.caption("🔍 วิเคราะห์รูปคำทีละพยางค์: " + " | ".join(ผลวิเคราะห์))
                st.write("---")
